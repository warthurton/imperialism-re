"""Generate winmm_sites.h from GOG's winmm.dll: the exact original bytes of the three
buffer-recycle blocks the shim replaces (so the shim can refuse to patch any other build).

usage: python -I gen_winmm_sites.py <path-to-GOG-winmm.dll> <out.h>
"""
import struct, sys

path, out = sys.argv[1], sys.argv[2]
d = open(path, 'rb').read()
pe = struct.unpack_from('<I', d, 0x3c)[0]
opt = pe + 24
base = struct.unpack_from('<I', d, opt + 28)[0]
size_of_image = struct.unpack_from('<I', d, opt + 56)[0]
timestamp = struct.unpack_from('<I', d, pe + 8)[0]
nsec = struct.unpack_from('<H', d, pe + 6)[0]
osz = struct.unpack_from('<H', d, pe + 20)[0]
secs = [struct.unpack_from('<IIII', d, opt + osz + i * 40 + 8) for i in range(nsec)]  # vsize, rva, rawsize, rawptr


def off(va):
    rva = va - base
    for vs, a, rs, rp in secs:
        if a <= rva < a + max(vs, rs):
            return rva - a + rp
    raise SystemExit('address not in any section: %#x' % va)


# name, first byte, one-past-last byte, where to resume after the replaced block
SITES = [
    ('S1', 0x6AB445C2, 0x6AB4460B, 0x6AB4459B),   # cleanup loop (the one that crashed)
    ('S2', 0x6AB449E8, 0x6AB44A3A, 0x6AB4498C),   # feed path recycle
    ('S3', 0x6AB44A88, 0x6AB44AD1, 0x6AB44A5B),   # second cleanup loop
]

lines = ['/* generated by gen_winmm_sites.py -- do not edit */',
         '#define WINMM_BASE        0x%08Xu' % base,
         '#define WINMM_TIMESTAMP   0x%08Xu' % timestamp,
         '#define WINMM_SIZEOFIMAGE 0x%08Xu' % size_of_image,
         '#define WINMM_SLOT_TABLE  0x6AB57820u   /* WAVEHDR* table[3] */',
         '#define WINMM_HWO         0x6AB57834u   /* HWAVEOUT global */',
         '#define WINMM_UNPREP_THUNK 0x6AB4A01Cu  /* jmp [waveOutUnprepareHeader] */',
         '#define WINMM_FREE_THUNK   0x6AB49BE0u  /* jmp [msvcrt!free] */',
         '']
for name, a, b, resume in SITES:
    bs = d[off(a):off(b)]
    lines.append('#define WINMM_%s_VA     0x%08Xu' % (name, a))
    lines.append('#define WINMM_%s_RESUME 0x%08Xu' % (name, resume))
    lines.append('static const unsigned char WINMM_%s_ORIG[%d] = {' % (name, len(bs)))
    for i in range(0, len(bs), 16):
        lines.append('    ' + ', '.join('0x%02X' % x for x in bs[i:i + 16]) + ',')
    lines.append('};')
    lines.append('')
open(out, 'w').write('\n'.join(lines) + '\n')
print('wrote', out, 'base %#x timestamp %#x sizeofimage %#x' % (base, timestamp, size_of_image))
for name, a, b, r in SITES:
    print(name, hex(a), b - a, 'bytes, resume', hex(r))
